/**
 * Write src/lib/contributors.generated.ts and public/contributors/*.png from the
 * repository's public contributor list (people only, bots left out, most
 * contributions first) and its star count. Run `bun run gen:contributors`
 * before a release.
 */
import { mkdir, writeFile } from "node:fs/promises";

const REPO = "vstorm-co/agenticos";
const API = "https://api.github.com";
const headers = { Accept: "application/vnd.github+json", "User-Agent": "agenticos-landing" };

async function json(url) {
  const response = await fetch(url, { headers });
  if (!response.ok) throw new Error(`${url} answered ${response.status}`);
  return response.json();
}

const repo = await json(`${API}/repos/${REPO}`);
const list = await json(`${API}/repos/${REPO}/contributors?per_page=100`);
const people = list.filter((entry) => entry.type === "User");
await mkdir(new URL("../public/contributors/", import.meta.url), { recursive: true });

const rows = [];
for (const person of people) {
  const profile = await json(`${API}/users/${person.login}`);
  const avatar = await fetch(`${person.avatar_url}&s=128`, { headers });
  if (!avatar.ok) throw new Error(`avatar for ${person.login} answered ${avatar.status}`);
  await writeFile(new URL(`../public/contributors/${person.login}.png`, import.meta.url), Buffer.from(await avatar.arrayBuffer()));
  rows.push({
    login: person.login,
    name: profile.name ?? person.login,
    contributions: person.contributions,
    url: person.html_url,
    avatar: `/contributors/${person.login}.png`,
  });
}

const out = `// AUTO-GENERATED by scripts/gen-contributors.mjs from the public GitHub API - do not edit by hand.

export interface Contributor {
  readonly login: string;
  readonly name: string;
  readonly contributions: number;
  readonly url: string;
  readonly avatar: string;
}

export const CONTRIBUTORS: readonly Contributor[] = ${JSON.stringify(rows, null, 2)};

/** The star count when this file was generated; the page refreshes it in the browser. */
export const STARS_AT_BUILD = ${repo.stargazers_count};
`;
await writeFile(new URL("../src/lib/contributors.generated.ts", import.meta.url), out);
console.log(`wrote ${rows.length} contributors`);
