/**
 * Write src/lib/logos.generated.ts: the full-colour service marks the page draws,
 * taken from the `logos` set (gilbarbara/logos, CC0) through @iconify-json/logos.
 * Adding a mark is adding a row to LOGOS and re-running `bun run gen:logos`.
 */
import { readFile, writeFile } from "node:fs/promises";

const LOGOS = {
  slack: "slack-icon",
  gmail: "google-gmail",
  gdrive: "google-drive",
  gcalendar: "google-calendar",
  notion: "notion-icon",
  github: "github-icon",
  linear: "linear-icon",
  figma: "figma",
  jira: "jira",
  confluence: "confluence",
  postgres: "postgresql",
  telegram: "telegram",
  mattermost: "mattermost-icon",
  microsoft: "microsoft-icon",
  onedrive: "microsoft-onedrive",
  s3: "aws-s3",
  supabase: "supabase-icon",
  sentry: "sentry-icon",
  asana: "asana-icon",
  webhooks: "webhooks",
  claude: "claude-icon",
  python: "python",
  fastapi: "fastapi-icon",
  nextjs: "nextjs-icon",
  docker: "docker-icon",
  valkey: "valkey-icon",
  linkedin: "linkedin-icon",
  x: "x",
};

const set = JSON.parse(await readFile(new URL("../node_modules/@iconify-json/logos/icons.json", import.meta.url), "utf8"));
const entries = Object.entries(LOGOS).map(([name, id]) => {
  const icon = set.icons[id];
  if (icon === undefined) throw new Error(`logos has no icon "${id}"`);
  const width = icon.width ?? set.width ?? 256;
  const height = icon.height ?? set.height ?? 256;
  return `  ${JSON.stringify(name)}: { viewBox: ${JSON.stringify(`0 0 ${width} ${height}`)}, body: ${JSON.stringify(icon.body)} },`;
});

const out = `// AUTO-GENERATED by scripts/gen-logos.mjs - do not edit by hand.
// Full-colour service marks from the \`logos\` set (https://github.com/gilbarbara/logos),
// CC0 1.0. The marks are their owners' trademarks; they identify connection options.

export interface ServiceLogo {
  readonly viewBox: string;
  /** Inner SVG markup, gradients included. */
  readonly body: string;
}

export const SERVICE_LOGOS = {
${entries.join("\n")}
} as const satisfies Record<string, ServiceLogo>;

export type ServiceName = keyof typeof SERVICE_LOGOS;
`;
await writeFile(new URL("../src/lib/logos.generated.ts", import.meta.url), out);
console.log(`wrote ${entries.length} logos`);
