/**
 * Write src/lib/logos.generated.ts: the full-colour service marks the page draws,
 * taken from the `logos` set (gilbarbara/logos, CC0) through @iconify-json/logos,
 * and, for marks that set lacks, from simple-icons (CC0) in each brand's colour.
 * Adding a mark is adding a row to LOGOS or SIMPLE and re-running `bun run gen:logos`.
 */
